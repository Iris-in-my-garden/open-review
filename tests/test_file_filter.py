from openreview.repo.diff_parser import DiffParser
from openreview.review.file_filter import (
    REVIEW,
    SKIP,
    classify_file,
    filter_parsed_diff,
    summarize_skipped,
)


def _file(
    filename: str,
    *,
    patch: str | None = "@@ -0,0 +1,1 @@\n+x = 1\n",
    status: str = "modified",
    additions: int = 1,
    deletions: int = 0,
):
    return DiffParser.parse_file(
        {
            "filename": filename,
            "status": status,
            "additions": additions,
            "deletions": deletions,
            "patch": patch,
        }
    )


