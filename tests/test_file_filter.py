def test_filter_parsed_diff_keeps_only_reviewable_files():
    diff = DiffParser.parse_diff(
        [
            {
                "filename": "src/app.py",
                "status": "modified",
                "additions": 1,
                "deletions": 0,
                "patch": "@@ -0,0 +1,1 @@\n+x = 1\n",
            },
            {
                "filename": "README.md",
                "status": "modified",
                "additions": 2,
                "deletions": 1,
                "patch": "@@ -1 +1,2 @@\n-old\n+new\n+more\n",
            },
            {
                "filename": "package-lock.json",
                "status": "modified",
                "additions": 10,
                "deletions": 10,
                "patch": "@@ -1 +1 @@\n-a\n+b\n",
            },
        ]
    )

    result = filter_parsed_diff(diff)

    assert [file.filename for file in result.diff.files] == ["src/app.py"]
    assert result.diff.total_additions == 1
    assert result.diff.total_deletions == 0
    assert len(result.skipped) == 2
    assert result.skipped_summary() == "docs 1、lockfile 1"


def test_summarize_skipped_handles_serialized_decisions():
    summary = summarize_skipped(
        [
            {"category": "data"},
            {"category": "data"},
            {"category": "docs"},
        ]
    )

    assert summary == "data 2、docs 1"


