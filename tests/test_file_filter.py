from openreview.repo.diff_parser import DiffParser
from openreview.review.file_filter import (
    REVIEW,
    SKIP,
    classify_file,
    filter_parsed_diff,
    summarize_skipped,
)


def _file(
    filename: str,
    *,
    patch: str | None = "@@ -0,0 +1,1 @@\n+x = 1\n",
    status: str = "modified",
    additions: int = 1,
    deletions: int = 0,
):
    return DiffParser.parse_file(
        {
            "filename": filename,
            "status": status,
            "additions": additions,
            "deletions": deletions,
            "patch": patch,
        }
    )


def test_lockfile_is_skipped():
    decision = classify_file(_file("package-lock.json"))

    assert decision.action == SKIP
    assert decision.category == "lockfile"


def test_image_without_text_patch_is_skipped_as_binary():
    decision = classify_file(_file("assets/logo.png", patch=None, status="added"))

    assert decision.action == SKIP
    assert decision.category == "binary"


def test_textual_static_asset_is_skipped():
    decision = classify_file(_file("assets/icon.svg"))

    assert decision.action == SKIP
    assert decision.category == "asset"


def test_generated_output_path_and_name_are_skipped():
    assert classify_file(_file("dist/app.js")).category == "generated"
    assert classify_file(_file("src/api.pb.go")).category == "generated"


def test_generated_marker_in_added_lines_is_skipped():
    patch = (
        "@@ -0,0 +1,2 @@\n"
        "+# Code generated by protoc-gen. DO NOT EDIT.\n"
        "+VALUE = 1\n"
    )

    decision = classify_file(_file("src/generated_client.py", patch=patch))

    assert decision.action == SKIP
    assert decision.category == "generated"


